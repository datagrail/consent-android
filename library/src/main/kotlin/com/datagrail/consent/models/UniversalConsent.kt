package com.datagrail.consent.models

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/**
 * Signature material returned by the customer-provided `getSignature` callback.
 *
 * The DataGrail SDK never computes the HMAC itself — the shared secret lives only on the
 * customer's backend and at the DataGrail edge. The SDK builds the canonical string-to-sign,
 * generates the per-write timestamp and nonce itself, and hands them to the callback inside a
 * [UniversalConsentSigningPayload]. The customer's backend computes
 * `HMAC-SHA256(rawBytes(secretHex), payload.stringToSign)` and returns just the resulting
 * [signature] together with the [keyId] (identifies which secret was used, for rotation).
 *
 * The SDK — not the callback — owns the timestamp and nonce and sends them as the X-DG-Timestamp
 * / X-DG-Nonce headers, so they are deliberately NOT part of this return type.
 *
 * Two things the edge is strict about, so the backend MUST match them exactly:
 *  - Secret as raw bytes: the shared secret is 64 hex characters. Decode it to its 32 raw bytes
 *    and use THOSE as the HMAC key. Do NOT feed the 64-char hex string to the HMAC as ASCII /
 *    UTF-8 text — that is the single most common signing bug, and every signature computed that
 *    way fails to verify at the edge.
 *  - Sign the SDK's string verbatim: HMAC over [UniversalConsentSigningPayload.stringToSign]
 *    exactly as given. Do NOT rebuild the string, reorder fields, or substitute your own
 *    timestamp/nonce — the SDK already committed to the values it will send in the headers.
 *
 * [signature] is lowercase hex.
 *
 * @property signature Lowercase-hex HMAC-SHA256 signature computed by the customer backend.
 * @property keyId Identifier of the HMAC secret used (supports key rotation).
 */
data class UniversalConsentSignature(
    val signature: String,
    val keyId: String,
)

/**
 * Everything the customer backend needs to sign a single universal-consent write. Built by the
 * SDK and passed to the [SignatureProvider] callback immediately before the write.
 *
 * The SDK owns [timestamp] (device unix seconds) and [nonce] (128-bit CSPRNG value rendered as
 * 32 lowercase hex) and has already composed [stringToSign] as
 * `"{customerId}:{userHash}:{timestamp}:{nonce}"`. The backend MUST sign [stringToSign]
 * verbatim; the individual fields are exposed only for logging/validation. The same [nonce] and
 * [timestamp] that appear here are the ones the SDK sends in the X-DG-Nonce / X-DG-Timestamp
 * headers, so the callback must not regenerate or override them.
 *
 * SECURITY — bind signing to the authenticated user. The callback receives the RAW, pre-hash
 * [identifier] alongside the already-derived [userHash]. Because [setUserIdentifier] accepts an
 * arbitrary caller-supplied identifier, the signing backend MUST NOT sign a hash blindly: an
 * app-side actor who knows a victim's identifier (e.g. their email) could otherwise have the SDK
 * derive that victim's hash and get it signed, overwriting the victim's cross-device consent. The
 * backend MUST verify [identifier] matches its own authenticated session's user before signing,
 * and SHOULD recompute the hash from [identifier] itself rather than trusting the client-supplied
 * [userHash].
 *
 * @property stringToSign The exact canonical string to feed to HMAC-SHA256.
 * @property customerId The DataGrail customer id.
 * @property identifier The RAW user identifier the SDK was given, BEFORE normalization/hashing.
 *   Bind signing to this against the authenticated session; do not sign for an identifier the
 *   session does not own.
 * @property userHash The SHA-256 user hash (see `ConsentService.computeUserHash`). Derived on the
 *   device from [identifier]; the backend should recompute rather than trust it blindly.
 * @property timestamp Device unix timestamp in seconds, generated by the SDK.
 * @property nonce 128-bit per-write nonce as 32 lowercase hex, from the SDK's CSPRNG.
 */
data class UniversalConsentSigningPayload(
    val stringToSign: String,
    val customerId: String,
    val identifier: String,
    val userHash: String,
    val timestamp: Long,
    val nonce: String,
)

/**
 * Customer-provided signature provider. Invoked by the SDK immediately before a universal
 * consent write. It is a suspend function so the customer can call their own backend on an IO
 * dispatcher.
 *
 * The SDK hands the callback a fully-formed [UniversalConsentSigningPayload] — the canonical
 * [UniversalConsentSigningPayload.stringToSign] plus the SDK-owned timestamp and nonce. The
 * callback computes `HMAC-SHA256(rawBytes(secretHex), payload.stringToSign)` on its backend and
 * returns a [UniversalConsentSignature] carrying only the signature and keyId. The SDK owns and
 * sends the timestamp and nonce itself, so the callback neither generates nor returns them.
 *
 * The backend MUST verify [UniversalConsentSigningPayload.identifier] belongs to its authenticated
 * session before signing — see the security note on that type — so a caller cannot get a victim's
 * hash signed by handing the SDK someone else's identifier.
 */
typealias SignatureProvider = suspend (payload: UniversalConsentSigningPayload) -> UniversalConsentSignature

/**
 * Consent preferences as stored in / returned by the universal consent API. Unlike
 * [ConsentPreferences] (which uses a list of [CategoryConsent]), the universal consent wire
 * format uses a MAP of `{ categoryKey: Boolean }` for `cookieOptions`.
 */
@Serializable
data class UniversalConsentPreferences(
    @SerialName("isCustomised")
    val isCustomised: Boolean = false,
    @SerialName("cookieOptions")
    val cookieOptions: Map<String, Boolean> = emptyMap(),
)

/**
 * A universal consent record returned by `GET /universal_consent`.
 *
 * IMPORTANT: this data is RAW and UNRECONCILED. The server never computes an "effective"
 * consent state — it returns the stored [consentPreferences] plus the IAB signals
 * ([gpc], [tcfString], [gppString]) exactly as written. Clients MUST reconcile GPC locally
 * before acting on consent (see [GpcReconciliation]).
 */
@Serializable
data class UniversalConsentRecord(
    val status: String,
    @SerialName("consent_preferences")
    val consentPreferences: UniversalConsentPreferences? = null,
    @SerialName("consent_mode")
    val consentMode: String? = null,
    @SerialName("ccpa_optout")
    val ccpaOptout: Boolean = false,
    val platform: String? = null,
    @SerialName("policy_name")
    val policyName: String? = null,
    @SerialName("config_version")
    val configVersion: String? = null,
    @SerialName("updated_at")
    val updatedAt: String? = null,
    // Raw IAB signals — passed through by the server, reconciled by the client.
    val gpc: Boolean = false,
    @SerialName("tcf_string")
    val tcfString: String? = null,
    @SerialName("gpp_string")
    val gppString: String? = null,
) {
    val isFound: Boolean get() = status == "found"
}

/**
 * Mandatory client-side signal reconciliation.
 *
 * The Universal Consent API returns raw, unreconciled data. When an opt-out signal applies —
 * either the record's stored `gpc` (recorded on the web, where GPC exists) or this device's live
 * ad-tracking signal — every SDK MUST suppress non-essential categories locally, regardless of
 * what the stored map says. The stored map may still show `marketing: true`, and a client that
 * naively trusts those booleans would fire marketing tags for an opted-out user.
 *
 * Suppression is one-directional. A signal may only turn categories OFF; it never turns one on.
 * Ad-tracking permission is not consent to marketing categories, and an unreadable signal is not
 * a choice at all, so neither state modifies the stored map.
 *
 * Effective state = stored preferences ∘ suppression, computed on-device and never persisted in
 * place of the raw stored choice.
 */
object SignalReconciliation {
    /**
     * Apply signal reconciliation to a cookie-options map.
     *
     * @param cookieOptions The raw stored `{ categoryKey: Boolean }` map.
     * @param suppress Whether an opt-out signal applies (device signal, stored GPC, or both).
     * @param essentialKeys The set of category keys that are essential / always-on and therefore
     *   never suppressed.
     * @return A new map where, when [suppress] is true, every non-essential category is forced to
     *   `false`. When [suppress] is false the input map is returned unchanged.
     */
    fun reconcile(
        cookieOptions: Map<String, Boolean>,
        suppress: Boolean,
        essentialKeys: Set<String>,
    ): Map<String, Boolean> {
        if (!suppress) return cookieOptions
        return cookieOptions.mapValues { (key, enabled) ->
            if (essentialKeys.contains(key)) enabled else false
        }
    }
}
